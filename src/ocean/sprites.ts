const spriteCache = new Map<string, HTMLCanvasElement>();

export function getSpriteCanvas(
  shape: ShapeId,
  palette: string[],
  flip: boolean,
  scale: number,
): HTMLCanvasElement {
  const key = `${shape}|${palette.join(",")}|${flip ? 1 : 0}|${scale}`;
  const hit = spriteCache.get(key);
  if (hit) return hit;

  const rows = SHAPES[shape];
  const h = rows.length;
  const w = rows[0]?.length ?? 1;
  const c = document.createElement("canvas");
  c.width = w * scale;
  c.height = h * scale;
  const ctx = c.getContext("2d")!;
  ctx.imageSmoothingEnabled = false;

  for (let y = 0; y < h; y++) {
    const row = rows[y]!;
    for (let x = 0; x < w; x++) {
      const srcX = flip ? w - 1 - x : x;
      const ch = row[srcX];
      if (!ch || ch === ".") continue;
      const idx = ch.charCodeAt(0) - 48;
      const color = palette[idx] ?? palette[0] ?? "#fff";
      ctx.fillStyle = color;
      ctx.fillRect(x * scale, y * scale, scale, scale);
    }
  }

  spriteCache.set(key, c);
  return c;
}

export function spriteSize(shape: ShapeId): { w: number; h: number } {
  const rows = SHAPES[shape];
  return { w: rows[0]?.length ?? 1, h: rows.length };
}
